const K = 100; // pixels par degré de latitude
const LON0 = -5;
const LAT0 = 51.3;
const COS = Math.cos((46.5 * Math.PI) / 180);

export const projectFR = (lon: number, lat: number): [number, number] => [(lon - LON0) * COS * K, (LAT0 - lat) * K];

const toPath = (list: [number, number][]) =>
  list
    .map(([lon, lat], i) => {
      const [x, y] = projectFR(lon, lat);
      return `${i ? 'L' : 'M'}${x.toFixed(1)},${y.toFixed(1)}`;
    })
    .join(' ') + ' Z';

